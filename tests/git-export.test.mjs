import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, mkdir, readFile, writeFile, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { execFileSync } from 'node:child_process';
import { snapshotFromGit } from '../src/server/git-export.js';
import { stringifyPost } from '../src/admin/content-model.js';
const canonical = JSON.parse(await readFile(new URL('../src/data/site.json', import.meta.url), 'utf8'));
const png = Buffer.from('iVBORw0KGgoAAAANSUhEUgAAAAEAAAABCAQAAAC1HAwCAAAAC0lEQVR42mNk+A8AAQUBAScY42YAAAAASUVORK5CYII=', 'base64');
const post = slug => stringifyPost({ slug, status: 'published', data: { title: slug, description: 'fixture', category: '软件工程与系统', pubDate: '2026-10-15', tags: [] }, body: '![published](/images/posts/public.png)' });
test('Git migration pins current main, preserves pending settings/media, and never resurrects deleted branch articles', async t => {
  const directory = await mkdtemp(join(tmpdir(), 'huaovo-git-test-')); t.after(() => rm(directory, { recursive: true, force: true }));
  const git = (...args) => execFileSync('git', args, { cwd: directory, stdio: ['ignore', 'pipe', 'pipe'] }).toString().trim();
  git('init', '-b', 'main'); git('config', 'user.name', 'Fixture'); git('config', 'user.email', 'fixture@example.invalid');
  for (const path of ['src/content/posts', 'src/data', 'public/images/posts']) await mkdir(join(directory, path), { recursive: true });
  await writeFile(join(directory, 'src/data/site.json'), JSON.stringify(canonical));
  await writeFile(join(directory, 'src/content/posts/deleted-demo.md'), post('deleted-demo'));
  await writeFile(join(directory, 'public/images/posts/public.png'), png); git('add', '.'); git('commit', '-qm', 'old main');
  const old = git('rev-parse', 'HEAD');
  await rm(join(directory, 'src/content/posts/deleted-demo.md'));
  await writeFile(join(directory, 'src/content/posts/real-article.md'), post('real-article')); git('add', '.'); git('commit', '-qm', 'current main');
  const current = git('rev-parse', 'HEAD');
  git('checkout', '-b', 'pending-settings', old);
  const pending = structuredClone(canonical); pending.home.title = 'Unpublished home'; pending.about.coverImage = '/images/posts/pending.png';
  await writeFile(join(directory, 'src/data/site.json'), JSON.stringify(pending)); git('add', '.'); git('commit', '-qm', 'pending settings');
  git('checkout', '-b', 'pending-media', old); await writeFile(join(directory, 'public/images/posts/pending.png'), png); git('add', '.'); git('commit', '-qm', 'pending media');
  const { snapshot, provenance, objects } = await snapshotFromGit({ cwd: directory, publishedRef: 'main', settingsRef: 'pending-settings', mediaRef: 'pending-media' });
  assert.equal(provenance.published.sha, current); assert.equal(snapshot.posts.length, 1); assert.equal(snapshot.posts[0].slug, 'real-article');
  assert.equal(snapshot.settings.published.home.title, canonical.home.title); assert.equal(snapshot.settings.draft.home.title, pending.home.title);
  assert.equal(snapshot.media.find(media => media.name === 'public.png').public, true);
  assert.equal(snapshot.media.find(media => media.name === 'pending.png').public, false);
  assert.equal(objects.size, 2); assert.deepEqual(objects.get('media/pending.png'), new Uint8Array(png));
});
